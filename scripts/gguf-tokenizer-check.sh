#!/usr/bin/env bash
# The GGUF tokenizer against llama.cpp's own: vocabularies are generated (no weights, nothing is downloaded) and the same
# strings go through `llama-tokenize` and through GgufModel.tokenizer(...); every id must be equal.
#
# usage: scripts/gguf-tokenizer-check.sh [options]
#
#   For every `tokenizer.ggml.pre` value the engine knows (and the absent key) a byte-level BPE vocabulary with a merge
#   for every pair of byte symbols, so that every boundary between two pre-tokenizer pieces shows in the ids, and three
#   SentencePiece kinds (Llama-2-like, equal scores, Gemma-like with add_space_prefix=false, Phi-3-like with its
#   whitespace-stripping markers); a corpus of ~1700 strings (contractions, digits, CJK, accents, emoji, whitespace,
#   code, special tokens in the text, random strings over a Unicode alphabet) and a sweep over the code points. Then
#   the BOS rules (add_bos_token present / absent) against `llama-tokenize` without --no-bos.
#
#   prints PASS / FAIL with the number of equal strings per vocabulary and exits 1 on a difference. When
#   llama-tokenize is not installed (LLAMA_TOKENIZE=/path, or on the PATH) it says so and exits 0.
#
# options (passed to GgufTokenizerLlamaCpp check):
#   --only TEXT          only the vocabularies whose label contains TEXT ("qwen", "spm", "bos")
#   --groups true        one vocabulary per distinct (regexes, flags) group instead of every pre value
#   --randoms N          random strings (default 1500)
#   --sweep STEP         every STEP-th code point of --sweep-from..--sweep-to in four contexts (default 61 over
#                        0x20..0x30000; 1 = all of them, 0 = none; characters assigned in newer Unicode than
#                        llama.cpp's tables are left out, see docs/16-gguf.md 16.12)
#   --gguf FILE          a real GGUF (repeatable) instead of the generated vocabularies: its first control token separates
#                        the strings; llama.cpp's models/ggml-vocab-*.gguf, or any model file
#   --paragraphs DIR     add the paragraphs of the Markdown files under DIR to the corpus
#   --show N             differing strings printed per vocabulary (default 4)
#   -Dgguf.tok.seed=N    (env JAVA_OPTS) another merge order of the generated byte-pair merges
#
# The ids llama-tokenize gave for a fixed corpus are also stored (src/test/resources/gguf/vocab/synthetic-llama-cpp.txt.gz)
# and checked by GgufTokenizerTest during `mvn test` without llama.cpp; to refresh them after changing the corpus:
#   java ... org.robomiri.jllm.GgufTokenizerLlamaCpp record src/test/resources/gguf/vocab/synthetic-llama-cpp.txt.gz
set -euo pipefail
cd "$(dirname "$0")/.."
[ -x /opt/homebrew/opt/openjdk@26/bin/java ] && [ -z "${JAVA_HOME:-}" ] && export JAVA_HOME=/opt/homebrew/opt/openjdk@26
export JAVA_HOME="${JAVA_HOME:?set JAVA_HOME to a JDK 26}"
MVN="${MVN:-mvn}"

LT="${LLAMA_TOKENIZE:-$(command -v llama-tokenize || true)}"
if [ -z "$LT" ] && [ -x /opt/homebrew/bin/llama-tokenize ]; then LT=/opt/homebrew/bin/llama-tokenize; fi
if [ -z "$LT" ]; then
  echo "llama-tokenize is not installed (brew install llama.cpp, or set LLAMA_TOKENIZE): GGUF tokenizer comparison skipped"
  exit 0
fi
export LLAMA_TOKENIZE="$LT"

if [ ! -d target/classes ] || [ ! -d target/test-classes ] || [ -n "$(find src/main src/test -newer target/test-classes/org/robomiri/jllm/GgufTokenizerLlamaCpp.class -name '*.java' 2>/dev/null | head -1)" ]; then
  "$MVN" -q -o test-compile
fi
# shellcheck disable=SC2086
exec "$JAVA_HOME/bin/java" --add-modules jdk.incubator.vector ${JAVA_OPTS:-} -cp target/classes:target/test-classes \
  org.robomiri.jllm.GgufTokenizerLlamaCpp check "$@"
